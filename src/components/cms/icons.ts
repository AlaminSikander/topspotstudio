export const iconFor = (name?: string | null): LucideIcon | undefined => (name ? ICON_MAP[name as IconName] : undefined);

/** Renders an editor-chosen icon by name (static lookup, so it is safe to use during render). */
export function CmsIcon({ icon, ...props }: { icon?: string | null } & Omit<ComponentProps<LucideIcon>, "name">) {
  const Icon = icon ? ICON_MAP[icon as IconName] : undefined;
  return Icon ? createElement(Icon, props) : null;
}
